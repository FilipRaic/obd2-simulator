BW_MM, BH_MM = 130.0, 115.0
FP_POS = {}
try:
    import pcbnew as _pcb
    _bp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "obd2-simulator.kicad_pcb")
    _b = _pcb.LoadBoard(_bp)
    _bb = _b.GetBoardEdgesBoundingBox()
    _x0 = _pcb.ToMM(_bb.GetX()); _y1 = _pcb.ToMM(_bb.GetY() + _bb.GetHeight())
    BW_MM = round(_pcb.ToMM(_bb.GetWidth()))
    BH_MM = round(_pcb.ToMM(_bb.GetHeight()))
    for _fp in _b.GetFootprints():
        _p = _fp.GetPosition()
        FP_POS[_fp.GetReference()] = (_pcb.ToMM(_p.x) - _x0, _y1 - _pcb.ToMM(_p.y))
except Exception as _e:                       # pokrenuto obicnim pythonom
    print("note: pcbnew unavailable (%s), falling back to the stored size" % _e)

SC = 13  # mm -> px
MX, MY = 90, 120
def bx(x): return MX + x*SC
def by(y): return MY + (BH_MM-y)*SC   # y measured from the bottom

def zone_box(refs, pad=4.0):
    """Bounding box of a component group, from the actual board positions."""
    pts = [FP_POS[r] for r in refs if r in FP_POS]
    if not pts:
        return None
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return (max(0.5, min(xs) - pad), max(0.5, min(ys) - pad),
            min(BW_MM - 0.5, max(xs) + pad), min(BH_MM - 0.5, max(ys) + pad))


"""Generator of the project figures (schematics, block diagrams, zones) for the
OBD-II simulator, revision v0.7.

The figures are drawn BY HAND here, they are not derived from the board, so they
do not update themselves when the board changes.

    python generate_figures.py

Until 23.08.2026. the drawing calls carried Croatian labels and an English run
translated them through a TRANSLATIONS table at the bottom of this file. The
Croatian pass had not been used since 15.08.2026., so the labels are written in
English directly now and the table is gone. The written documentation uses a
different generator, see PROVENANCE below.
"""
import io, os, sys

W, H = 1600, 1000
INK = "#1c2733"; DIM = "#5c6b7a"; LINE = "#8fa0b0"
ACC = "#b8860b"; RED = "#b03030"; GRN = "#2e7d4f"; BG = "#ffffff"; FILL = "#f3f6f9"

# Stamped into every figure, right inside the root element. These files get
# opened on their own, far from any README, and the two same-named figure sets
# are easy to confuse. No double hyphens anywhere: that is illegal in XML
# comments.
PROVENANCE = ("Generated by hardware/kicad/scripts/generate_figures.py. Repository figure, English. The project's written documentation uses a separate figure set from its own generator, with the same file names but different drawings. Edit this file by editing the generator, never by hand.")

def svg(w, h, body):
    # A double hyphen inside an XML comment makes the file unparseable, and an
    # SVG viewer will simply show nothing. Writing "--lang hr" in the Croatian
    # stamp broke all nine figures on 15.08.2026., so the rule is enforced here
    # rather than trusted.
    if "--" in PROVENANCE:
        raise ValueError("PROVENANCE contains a double hyphen, which is "
                         "illegal inside an XML comment")
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">'
            '<!-- %s -->'
            '<rect width="%d" height="%d" fill="%s"/>'
            '<g font-family="DejaVu Sans, Arial, sans-serif">%s</g></svg>'
            % (w, h, w, h, PROVENANCE, w, h, BG, body))

def box(x, y, w, h, title, sub="", fill=FILL, stroke=INK, tsize=17):
    title = title; sub = sub
    title = title.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    sub = sub.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = '<rect x="%d" y="%d" width="%d" height="%d" rx="6" fill="%s" stroke="%s" stroke-width="2"/>' % (x, y, w, h, fill, stroke)
    s += '<text x="%d" y="%d" text-anchor="middle" font-size="%d" font-weight="600" fill="%s">%s</text>' % (x+w/2, y+(24 if sub else h/2+6), tsize, INK, title)
    if sub:
        for i, ln in enumerate(sub.split("|")):
            s += '<text x="%d" y="%d" text-anchor="middle" font-size="13" fill="%s">%s</text>' % (x+w/2, y+46+i*17, DIM, ln)
    return s

def wire(pts, color=INK, w=2, dash=None):
    d = " ".join(("M %d %d" % p) if i == 0 else ("L %d %d" % p) for i, p in enumerate(pts))
    da = ' stroke-dasharray="6 4"' if dash else ''
    return '<path d="%s" fill="none" stroke="%s" stroke-width="%d"%s/>' % (d, color, w, da)

def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

def lbl(x, y, t, size=13, anchor="start", color=DIM, weight="400", mono=True):
    t = esc(t)
    fam = ' font-family="DejaVu Sans Mono, Consolas, monospace"' if mono else ''
    return '<text x="%d" y="%d" text-anchor="%s" font-size="%d" fill="%s" font-weight="%s"%s>%s</text>' % (x, y, anchor, size, color, weight, fam, t)

def title(t, sub=""):
    t = t; sub = sub
    s = '<text x="40" y="46" font-size="26" font-weight="700" fill="%s">%s</text>' % (INK, t)
    if sub: s += '<text x="40" y="72" font-size="15" fill="%s">%s</text>' % (DIM, sub)
    s += '<line x1="40" y1="88" x2="%d" y2="88" stroke="%s" stroke-width="2"/>' % (W-40, LINE)
    return s

def dot(x, y, c=INK):
    return '<circle cx="%d" cy="%d" r="4" fill="%s"/>' % (x, y, c)

def gnd(x, y):
    return (wire([(x, y), (x, y+14)]) +
            '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="2"/>' % (x-11, y+14, x+11, y+14, INK) +
            '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="2"/>' % (x-7, y+19, x+7, y+19, INK) +
            '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="2"/>' % (x-3, y+24, x+3, y+24, INK))

OUT = os.path.dirname(os.path.abspath(__file__))
def write(name, w, h, body):
    p = os.path.join(OUT, "fig", name + ".svg")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8").write(svg(w, h, body))
    return p

